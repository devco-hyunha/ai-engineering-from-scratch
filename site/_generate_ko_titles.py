def existing_korean_titles():
    titles = {}
    for doc in ROOT.glob("phases/**/docs/ko.md"):
        first = doc.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ").strip()
        first = re.sub(r"\s*\([^()]*[A-Za-z][^()]*\)\s*$", "", first).strip()
        lesson_path = doc.parent.parent.relative_to(ROOT).as_posix()
        titles[lesson_path] = first
    return titles


def structural_rewrite(name):
    # X for Y -> Y를 위한 X (simple two-part titles)
    m = re.match(r"^(.+?) for (.+)$", name)
    if m and ":" not in m.group(1) and len(m.group(2).split()) <= 4:
        return f"{m.group(2)}를 위한 {m.group(1)}"
    m = re.match(r"^(.+?) with (.+)$", name)
    if m and ":" not in m.group(1) and len(m.group(2).split()) <= 6:
        return f"{m.group(2)} 활용 {m.group(1)}"
    m = re.match(r"^Introduction to (.+)$", name)
    if m:
        return f"{m.group(1)} 입문"
    return name


def translate(name):
    if name in EXACT:
        return EXACT[name]

    title = structural_rewrite(name)
    for english, korean in sorted(PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
        title = title.replace(english, korean)
    for english, korean in sorted(WORDS.items(), key=lambda item: len(item[0]), reverse=True):
        title = re.sub(rf"(?<![A-Za-z]){re.escape(english)}(?![A-Za-z])", korean, title)

    title = re.sub(r"\s+", " ", title)
    title = re.sub(r"\s+([,:)])", r"\1", title)
    title = re.sub(r"([(])\s+", r"\1", title)
    title = re.sub(r"\s*및\s*$", "", title)
    return title.strip(" -—:")


