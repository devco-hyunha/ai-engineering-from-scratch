def load_lessons():
    if SOURCE.exists():
        return json.loads(SOURCE.read_text(encoding="utf-8"))
    # Fallback: extract from data.js with Node when the cache JSON is absent.
    import subprocess
    script = (
        "const fs=require('fs');const vm=require('vm');"
        "const s={};vm.runInNewContext(fs.readFileSync('site/data.js','utf8')+';\\nthis.PHASES=PHASES;',s);"
        "const out=[];for(const p of s.PHASES){for(const l of p.lessons){"
        "const m=String(l.url||'').match(/(phases\\/[^/]+\\/[^/]+)/);"
        "out.push({path:m?m[1]:'',name:l.name,phase:p.id});}}"
        "process.stdout.write(JSON.stringify(out));"
    )
    raw = subprocess.check_output(["node", "-e", script], cwd=str(ROOT))
    return json.loads(raw.decode("utf-8"))


